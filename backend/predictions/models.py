from django.db import models
from students.models import Student, get_performance_category


class Prediction(models.Model):
    """
    Stores historical learning outcome predictions generated by the ML pipeline.
    """
    student = models.ForeignKey(
        Student,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='predictions',
        help_text="Associated student record (optional for exploratory what-if predictions)"
    )
    student_id_snapshot = models.CharField(
        max_length=50,
        blank=True,
        help_text="Snapshot of Student ID for audit continuity"
    )
    student_name_snapshot = models.CharField(
        max_length=150,
        blank=True,
        help_text="Snapshot of Student Name"
    )
    study_hours = models.FloatField(help_text="Input: Daily study hours")
    attendance_percentage = models.FloatField(help_text="Input: Attendance %")
    assignment_score = models.FloatField(help_text="Input: Assignment score")
    previous_exam_marks = models.FloatField(help_text="Input: Previous exam marks")

    predicted_marks = models.FloatField(help_text="Target output: Predicted final exam marks (0-100)")
    performance_category = models.CharField(
        max_length=50,
        help_text="Categorical performance band derived from predicted score"
    )
    model_version = models.CharField(
        max_length=50,
        default='RF-Regressor-v1.0',
        help_text="Identifier of the ML model used to generate prediction"
    )
    risk_factors = models.JSONField(
        default=list,
        blank=True,
        help_text="Identified academic friction factors (e.g. low attendance, low study hours)"
    )
    recommendations = models.JSONField(
        default=list,
        blank=True,
        help_text="Actionable faculty interventions"
    )
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-created_at']
        verbose_name = 'Prediction'
        verbose_name_plural = 'Predictions'

    def __str__(self):
        target = self.student_id_snapshot or "Exploratory Student"
        return f"Prediction for {target}: {self.predicted_marks:.1f}% ({self.performance_category})"

    @property
    def actual_marks(self):
        if self.student and self.student.final_exam_marks is not None:
            return self.student.final_exam_marks
        return None

    @property
    def variance(self):
        if self.actual_marks is not None:
            return round(self.predicted_marks - self.actual_marks, 2)
        return None
